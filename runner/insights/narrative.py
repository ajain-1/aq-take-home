"""Optional plain-language summary written by an LLM, constrained to verified findings.

The model only sees findings that already passed evidence verification, and every
sentence it returns must cite evidence IDs from them. Sentences citing unknown IDs, or
containing numbers that do not appear in the cited findings, are dropped.
"""

import json
import os
import re
import urllib.request
from typing import Any

OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"
DEFAULT_MODEL = os.environ.get("AQ_INSIGHTS_MODEL", "openai/gpt-4.1-mini")
NUMBER = re.compile(r"\d+(?:\.\d+)?")
EVIDENCE_ID = re.compile(r"\bE\d+\b")

PROMPT = """You summarize evaluation findings for a customer who wants to improve a coding task.
Use ONLY the findings below. Write 2-5 sentences: what most limits the pass rate, and what to change.
Every sentence must cite the evidence IDs (e.g. "E3") that support it. Do not add facts, numbers, or
speculation that the findings do not state.

Respond with JSON only: {{"sentences": [{{"text": "...", "evidence": ["E1"]}}]}}

Findings:
{findings}
"""


def _findings_block(report: dict[str, Any]) -> str:
    return "\n".join(
        f"- [{i['severity']}] {i['title']}: {i['detail']} (evidence: {', '.join(i['evidence'])})"
        for i in report["insights"]
    )


def _supported(sentence: dict[str, Any], report: dict[str, Any]) -> bool:
    cited = sentence.get("evidence") or []
    accepted = {e for insight in report["insights"] for e in insight["evidence"]}
    if not cited or any(e not in accepted for e in cited):
        return False
    support = (
        " ".join(f"{i['title']} {i['detail']}" for i in report["insights"] if set(cited) & set(i["evidence"]))
        + " "
        + " ".join(report["evidence"][e]["quote"] for e in cited)
    )
    text = EVIDENCE_ID.sub("", sentence.get("text", ""))
    return all(number in support for number in NUMBER.findall(text))


def _complete(prompt: str, model: str, api_key: str) -> str:
    body = json.dumps(
        {
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0,
            "response_format": {"type": "json_object"},
        }
    ).encode()
    request = urllib.request.Request(
        OPENROUTER_URL,
        data=body,
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read())["choices"][0]["message"]["content"]


def summarize(
    report: dict[str, Any], model: str = DEFAULT_MODEL, complete=_complete
) -> dict[str, Any] | None:
    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not report["insights"] or not api_key:
        return None
    try:
        sentences = json.loads(complete(PROMPT.format(findings=_findings_block(report)), model, api_key))[
            "sentences"
        ]
    except Exception:
        return None

    kept = [s for s in sentences if isinstance(s, dict) and _supported(s, report)]
    text = " ".join(f"{s['text'].strip()} [{', '.join(s['evidence'])}]" for s in kept)
    return {
        "text": text or "No sentence survived citation checks.",
        "model": model,
        "kept_sentences": len(kept),
        "dropped_sentences": len(sentences) - len(kept),
        "note": f"Generated by {model}; {len(sentences) - len(kept)} sentence(s) dropped for missing or "
        "unsupported citations. The findings above, not this summary, are the source of truth.",
    }
